export function triggerHaptic(pattern: number | number[] = 15, enabled: boolean = true) {
  if (!enabled || typeof window === 'undefined') return;
  try {
    if ('vibrate' in navigator) {
      navigator.vibrate(pattern);
    }
  } catch {}
}
